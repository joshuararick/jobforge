// Tiny localStorage wrapper. Everything JobForge knows lives on this device.
// Reads never throw: private mode / blocked storage just behaves like "empty".

const PREFIX = 'jobforge-';

export function load(key, fallback) {
  try {
    const raw = localStorage.getItem(PREFIX + key);
    return raw == null ? fallback : JSON.parse(raw);
  } catch {
    return fallback;
  }
}

export function save(key, value) {
  try {
    localStorage.setItem(PREFIX + key, JSON.stringify(value));
    return true;
  } catch {
    return false;
  }
}
